# 生成"给朋友"的压缩包：极简结构，打开先看到必读说明
#   合并转发搜索/
#     1_先看这个.txt
#     2_双击安装.bat
import os
import zipfile

SRC_BAT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ForwardSearch-Setup.bat')
OUT = r'G:\桌面\合并转发搜索-安装包.zip'
TOP = '合并转发搜索'

NOTE = """================================================
  合并转发搜索 · 安装前请看
================================================

【这是什么】

  一个 QQ 插件，解决一个很具体的问题：

  QQ 的"合并转发"会把一堆聊天记录打包成一张卡片。
  卡片外面只显示一小段摘要，里面几十条消息是什么，得点开才看得到。
  过几天想找"上次群里说过的那句话"，你只记得一句话的内容，
  却不知道它被装在哪张卡片里 —— 只能一张张点开翻。

  这个插件把这些卡片里的内容建成索引：
  你搜一句话，它直接把你送到那张卡片上。

  它不改你的聊天记录，也不往任何地方上传东西。


【一、装之前确认一件事】

  电脑上已经装了 QQ（新版 NT 界面，蓝白圆角图标那个）。
  没有的话，先去 https://qq.qq.com 下载安装，登录一次，再回来。

  别的都不用准备。安装包是离线的，不联网也能装。


【二、怎么装】

  双击  2_双击安装.bat

  如果弹出「Windows 已保护你的电脑」：
    点「更多信息」→「仍要运行」。
    这是 Windows 对网上下载的文件例行拦截，不是文件有问题。

  如果杀毒软件报毒，或者直接把文件删掉了：
    这个 bat 里面塞了一段编码数据，容易被误判。
    把它加进信任区再试。

  QQ 装在 C:\\Program Files 的，会弹一次授权，点「是」。

  装完它会问「现在打开 QQ 吗」，选是。


【三、装完怎么用】

  1. 进一个有合并转发卡片的群
  2. 按 Alt + S 打开搜索面板
  3. 第一次打开会有一个说明页，选「用内容补全模式」
  4. 点右下角「扫描历史」，弹窗点确定
  5. 等它跑完（几分钟，看你的聊天量）

  扫一次会把你所有有本地缓存的会话都过一遍，不用一个个群去点。

  ⚠ 刚登录的新电脑，本地还没有聊天记录，扫描会扫到 0 条。
    先进那个群往上翻几屏，让它把消息加载出来，再扫一次。


【四、怎么卸】

  再双击一次 2_双击安装.bat，
  它会检测到已经装过，问你：

    1 = 重新安装（更新）
    2 = 卸载

  选 2。卸载会把 QQ 还原成装之前的样子，
  你的聊天记录不受任何影响（都在腾讯服务器和 QQ 自己的数据里）。


【五、出问题了】

  QQ 打不开？
    再双击安装包，选 2 卸载，QQ 立刻恢复。

  按 Alt + S 没反应？
    QQ 设置 → LiteLoaderQQNT → 插件列表，
    看 forward-search 是不是启用状态。

  面板打开了但列表是空的？
    看上面第三节，先点「扫描历史」。

  QQ 更新之后插件不见了？
    重新双击安装包，选 1 重新安装，索引不会丢。


【六、必须知道的】

  · 这个插件改的是 QQ 客户端本身，用的是社区逆向出来的接口，
    不是腾讯提供的。腾讯没有授权，也不提供任何支持。

  · LiteLoaderQQNT 官方提示：QQ 可能把这类工具当作外挂，
    存在封号风险。介意的话，请用不常用的小号先试。

  · 本插件不联网、不上传任何内容。搜索结果只存在你自己电脑上：
    C:\\Users\\你的用户名\\AppData\\Local\\LiteLoaderQQNT\\data\\forward-search
    这是明文，想清理直接删这个文件夹。

  · 完全免费。如果你是花钱买到的，那是被人骗了。

  本项目仅供技术学习研究使用。
  源码：https://github.com/fushengzhenjun/LiteLoaderQQNT-Plugin-ForwardSearch

================================================
"""

if os.path.exists(OUT):
    os.remove(OUT)

with zipfile.ZipFile(OUT, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as z:
    z.writestr(TOP + '/1_先看这个.txt', NOTE.encode('utf-8-sig'))
    z.write(SRC_BAT, TOP + '/2_双击安装.bat')

print('生成: %s' % OUT)
print('大小: %d KB' % round(os.path.getsize(OUT) / 1024))
with zipfile.ZipFile(OUT) as z:
    for i in z.infolist():
        print('   %-32s %7d B' % (i.filename, i.file_size))
